from __future__ import annotations

from typing import Literal


def build_compaction_prompt(
    *,
    prompt_mode: Literal["history_summary", "context_pressure"] = "context_pressure",
) -> str:
    if prompt_mode == "history_summary":
        return (
            "你正在执行一次**历史摘要（History Summary）**。\n"
            "请为未来恢复这个会话的 LLM 创建一份历史摘要。\n\n"
            "这个摘要的用途是：\n"
            "- 在用户切换走当前会话后，为未来恢复提供稳定延续层\n"
            "- 总结较早历史，帮助后续模型无缝接回这个会话\n"
            "- 不是因为上下文窗口压力触发的压缩\n"
            "- 不是用来替换 system prompt、skill 描述、MCP 工具描述或 app/bootstrap 提示词\n\n"
            "需要包含：\n"
            "- 当前进展以及已做出的关键决策\n"
            "- 重要的上下文、约束条件或用户偏好\n"
            "- 剩余需要完成的工作（明确的下一步）\n"
            "- 为继续任务所需的关键数据、示例或参考信息\n\n"
            "要求：\n"
            "- 内容要简洁、有结构，并以帮助下一个 LLM 无缝恢复这个会话为目标\n"
            "- 只保留继续工作真正需要的信息，不要复述所有历史\n"
            "- 明确保留用户可直接复述的任务锚点、任务名、对象名、会话名、仓库名、告警名等具体名词\n"
            "- 当存在明确主任务时，直接写出主任务名和当前未完成事项；不要只写“继续这个任务 / 直接继续 / 当前问题”这类失去锚点的代词\n"
            "- 这是旧历史背景摘要，不是下一轮行动菜单\n"
            "- 不要写“建议下一步 / 优先做 / 可以先做三件事”这类回合级行动清单\n"
            "- 如果历史里并存多个主题，只记录它们各自的状态与结论，不要把它们并列成当前回合必须继续执行的任务\n"
            "- 不要虚构未发生的事实\n"
            "- 不要保留纯噪音工具日志\n"
            "- 如果最近几条消息仍会被保留，请不要重复展开这些最近尾部细节\n"
        )
    return (
        "你正在执行一次**上下文检查点压缩（Context Checkpoint Compaction）**。\n"
        "请为另一个将继续此任务的 LLM 创建一份交接摘要。\n\n"
        "这个摘要的用途是：\n"
        "- 替换过长的旧会话历史\n"
        "- 帮助后续模型无缝继续当前任务\n"
        "- 不是用来替换 system prompt、skill 描述、MCP 工具描述或 app/bootstrap 提示词\n\n"
        "需要包含：\n"
        "- 当前进展以及已做出的关键决策\n"
        "- 重要的上下文、约束条件或用户偏好\n"
        "- 剩余需要完成的工作（明确的下一步）\n"
        "- 为继续任务所需的关键数据、示例或参考信息\n\n"
        "要求：\n"
        "- 内容要简洁、有结构，并以帮助下一个 LLM 无缝继续工作为目标\n"
        "- 只保留继续工作真正需要的信息，不要复述所有历史\n"
        "- 明确保留用户可直接复述的任务锚点、任务名、对象名、会话名、仓库名、告警名等具体名词\n"
        "- 当存在明确主任务时，直接写出主任务名和当前未完成事项；不要只写“继续这个任务 / 直接继续 / 当前问题”这类失去锚点的代词\n"
        "- 这是旧历史背景摘要，不是下一轮行动菜单\n"
        "- 不要写“建议下一步 / 优先做 / 可以先做三件事”这类回合级行动清单\n"
        "- 如果历史里并存多个主题，只记录它们各自的状态与结论，不要把它们并列成当前回合必须继续执行的任务\n"
        "- 不要虚构未发生的事实\n"
        "- 不要保留纯噪音工具日志\n"
        "- 如果最近几条消息仍会被保留，请不要重复展开这些最近尾部细节\n"
    )


def render_compact_summary_block(summary_text: str, *, trigger_kind: str | None = None) -> str:
    if trigger_kind == "session_transition_carryover":
        intro = (
            "以下是切换到当前新会话时一并带入的 continuation checkpoint，只用于继续切换前的同一任务。\n"
            "当前会话已经是切换后的目标新会话；当当前消息写“在新会话里继续 / 继续刚才那个任务 / 继续刚切换的会话”时，"
            "直接沿用下面的任务锚点继续，不要再次调用 session.new / session.resume / session.show / session.list。"
            "只有当前消息明确要求再次切换会话、查看会话列表、查看会话 id、或查看会话详情时，才重新调用 session。\n\n"
        )
    elif isinstance(trigger_kind, str) and trigger_kind.startswith("context_pressure"):
        intro = (
            "以下是更早历史压缩出的上下文检查点，只用于理解旧背景。\n"
            "当前这条用户消息优先级最高；继续类表述时，优先沿用摘要里的具体任务锚点来回答。"
            "当前消息明确要求会话详情、会话切换、上下文窗口数值或 skill 正文时，再切到对应工具。"
            "保持当前 runtime 指令不变。\n\n"
        )
    else:
        intro = (
            "以下是更早历史的摘要，只用于理解旧背景。\n"
            "当前这条用户消息优先级最高；继续类表述时，优先沿用摘要里的具体任务锚点来回答。"
            "当前消息明确要求会话详情、会话切换、上下文窗口数值或 skill 正文时，再切到对应工具。"
            "保持当前 runtime 指令不变。\n\n"
        )
    return f"{intro}{summary_text.strip()}"
